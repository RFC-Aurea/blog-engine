#!/usr/bin/env python3
"""Build illustrations/medical.svg, the research-grade medical illustration library (Alifiya, 2026-10-26), and
illustrations/medical_parts.json (every part's viewBox, what it shows, and named anchor points for labels).

  python3 illustrations/build_medical.py

Textbook-style anatomy drawn cell by cell in medical colours on a white background. The parts live in
illustrations/medlib/ (one module per subject); seeded randomness keeps every build identical.
In an image HTML: put {{MEDICAL}} inside the <svg class="canvas">, then <use href="#m-..." x y width height/>.
A point (ax, ay) of a part lands at x + ax * width / vbWidth, y + ay * height / vbHeight (viewBoxes start at 0,0).
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from medlib import core, defs, embryo, genetics, ovary, tools  # noqa: E402

OUT = Path(__file__).with_name("medical.svg")
PARTS_OUT = Path(__file__).with_name("medical_parts.json")


def main():
    body = []
    for mod in (ovary, embryo, genetics, tools):
        body += mod.build()
    OUT.write_text('<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute">\n'
                   "<!-- generated by illustrations/build_medical.py; do not edit by hand. Parts and anchors: "
                   "illustrations/medical_parts.json -->\n" + defs.defs() + "\n".join(body) + "\n</svg>\n")
    import re
    ids = re.findall(r'\bid="([^"]+)"', OUT.read_text())
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        sys.exit(f"duplicate ids in medical.svg: {dupes}")
    PARTS_OUT.write_text(json.dumps(core.PARTS, indent=1) + "\n")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB) and {PARTS_OUT.name}: {', '.join(core.PARTS)}")


if __name__ == "__main__":
    main()
